#!/usr/bin/env python3
"""Bind the prospective-reference caveat to completed metadata checks."""
from __future__ import annotations

import importlib
import json

import pandas as pd

import wrr_r3_common as C

A = importlib.import_module("408_wrr_au_dependence_audit")
OUT = A.OUT


def main():
    summary = json.loads((OUT / "summary.json").read_text())
    qualification = json.loads((A.G.FIRST / "observed_reference_summary.json").read_text())
    acquisition = json.loads((A.G.FIRST / "daily_acquisition.json").read_text())
    roles = pd.read_csv(OUT / "role_support.csv")
    candidates = pd.read_csv(OUT / "station_hydrologic_scope.csv", dtype={"station_id": str}).fillna("")
    references = pd.read_csv(OUT / "original_qualified_references_scope.csv", dtype={"station_id": str}).fillna("")
    original = pd.read_csv(A.G.FIRST / "observed_reference_release.csv", dtype={"station_id": str})
    original = original.loc[original.observed_sampling_reference_eligible.eq(True)]
    blocks = pd.read_csv(OUT / "qualified_reference_blocks.csv")
    checks = []
    def check(name, passed):
        checks.append({"check": name, "passed": bool(passed)})
    check("all_original_metadata_candidates_retained", len(candidates) == summary["candidate_stations"] and not candidates.station_id.duplicated().any())
    keys = ["station_id", "year", "role", "independence_group"]
    check("original_qualified_station_years_and_roles_retained", set(map(tuple, references[keys].to_numpy())) == set(map(tuple, original[keys].to_numpy())) and len(references) == len(original))
    check("original_quality_summary_retained", len(references) == qualification["qualified_observed_sampling_station_years"] == summary["original_qualified_reference_station_years"])
    check("role_counts_match_original_polygon_qualification", roles.set_index("role").original_qualified_polygon_components.to_dict() == qualification["qualified_catchment_components_by_role"])
    check("unresolved_reference_stations_reported", references.loc[references.hydrologic_block.eq(""), "station_id"].nunique() == summary["qualified_reference_stations_pending_topology"])
    check("cross_role_hydrologic_screen_retained", int(blocks.cross_role_screen.sum()) == summary["qualified_reference_blocks_spanning_original_roles"])
    check("new_primary_errors_remain_sealed", not qualification["new_H30_prediction_errors_opened"] and not summary["new_temperature_values_or_H30_prediction_errors_opened"] and not references.primary_test_error_access_allowed.any())
    check("unmapped_stations_do_not_become_independent_singletons", int(candidates.hydrologic_block.eq("").sum()) == summary["stations_pending_attachment_or_metadata"])
    check("no_evaluation_or_role_change_from_connectivity", not summary["new_confirmation_completed"] and not summary["new_roles_assigned"] and not candidates.original_role_edited.any())
    check("remaining_weather_and_prior_pool_requirements_explicit", not summary["region_event_dependence_verified"] and not summary["earlier_opened_record_exclusion_fully_verified"])
    check("full_topology_connection_count_conserved", sum(summary["network"][key] for key in ("positive_physical_connection_rows", "nonpositive_endpoint_rows_excluded_from_connections")) == json.loads((A.G.OUT / "metadata_acquisition.json").read_text())["network_edges"])
    failures = [row["check"] for row in checks if not row["passed"]]
    if failures:
        raise RuntimeError(f"Metadata evidence conservation failed: {failures}")
    original_role = roles.set_index("role").original_qualified_polygon_components
    screened_role = roles.set_index("role").conservative_qualified_hydrologic_blocks
    order = ("development", "calibration", "test")
    original_counts = "/".join(str(original_role[role]) for role in order)
    screened_counts = "/".join(str(screened_role[role]) for role in order)
    note = (
        "% Generated by script 409 from the metadata and qualification results.\n"
        "A subsequent public-reference intake is separate from every evaluated cohort above. "
        f"BoM Water Data Online supplied {len(acquisition['results'])} Australian station daily archives; the intake checked {qualification['native_jobs']} native station-year intervals. "
        f"{summary['original_qualified_reference_station_years']} candidate station-years at {summary['original_qualified_reference_stations']} stations "
        f"passed the fixed daily-quality and observed-sampling requirements. Their original polygon-based development/calibration/test component counts are {original_counts}. "
        "These are qualification counts, not independent confirmation units or method effects.\n\n"
        "An additional metadata-only screen uses weak connectivity of every cached positive physical-node link, "
        "including shared upstream bifurcations and common downstream connections without a recruited gauge. "
        "Nonpositive outlet sentinels cannot merge distinct rivers. "
        f"The {summary['stations_with_verified_physical_graph_attachment']} mapped candidate stations form {summary['conservative_hydrologic_blocks_all_mapped_candidates']} conservative hydrologic blocks. "
        f"The mapped qualified references occupy {summary['conservative_qualified_hydrologic_blocks_total']} such blocks; "
        f"{summary['qualified_reference_blocks_spanning_original_roles']} span original roles, and {summary['qualified_reference_stations_pending_topology']} qualified station remains pending topology review. "
        f"Within-role counts become {screened_counts} and may share a block across roles, so they must not be summed as disjoint units. "
        "Conservative basin connectivity does not by itself prove shared-record leakage or independent regional weather. "
        "The source is the BoM Geofabric V3.3 network (\\url{https://www.bom.gov.au/water/geofabric/}), "
        "attributed to the Commonwealth of Australia (Bureau of Meteorology), 2022. "
        "Original roles and quality qualifications are preserved; no new target prediction error has been opened.\n\n"
        f"For the future three-method error allocation, the ideal one-threshold zero-failure floor is {summary['necessary_ideal_one_threshold_calibration_group_floor']} groups per calibration/evaluation role, "
        f"hence at least {summary['necessary_ideal_disjoint_calibration_plus_test_floor']} disjoint groups even before training and joint-power requirements. "
        "This is a necessary lower bound, not a recommended recruitment size. "
        f"The mapped pool alone is insufficient under this conservative grouping; {summary['stations_pending_attachment_or_metadata']} unmapped candidates remain unresolved rather than counted as zero eligible. "
        "Prior-pool exclusions, regional-event dependence, verified process attributes and new-population joint planning are still required. "
        "Acquiring reference records has therefore not completed a new confirmation or an independently backed natural-gap experiment.\n"
    )
    paper = C.ROOT / "paper/wrr/r9_au_reference_scope.tex"
    paper.write_text(note)
    pd.DataFrame(checks).to_csv(OUT / "checks.csv", index=False)
    C.write_json(OUT / "evidence_summary.json", {
        "all_passed": True, "checks_passed": len(checks), "checks_total": len(checks),
        "new_confirmation_completed": False, "primary_test_error_access_allowed": False,
        "original_role_count_order": "development/calibration/test",
        "original_polygon_role_components": original_counts,
        "conservative_hydrologic_role_blocks_not_disjoint": screened_counts,
        "same_qualified_station_years": len(references),
    })
    print(f"[409] {len(checks)}/{len(checks)} conservation checks; prospective SI caveat generated; no new confirmation", flush=True)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
